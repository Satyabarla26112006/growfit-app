  static FoodModel? findById(String id) {
    for (final food in foods) {
      if (food.id == id) {
        return food;
      }
    }
    return null;
  }

  // ============================================================
  // FIND BY CATEGORY
  // ============================================================

  static List<FoodModel> byCategory(String category) {
    return foods
        .where(
          (food) =>
              food.category.toLowerCase() ==
              category.toLowerCase(),
        )
        .toList();
  }

  // ============================================================
  // SEARCH
  // ============================================================

  static List<FoodModel> search(String query) {
    final normalizedQuery = query.trim().toLowerCase();

    if (normalizedQuery.isEmpty) {
      return foods;
    }

    return foods
        .where(
          (food) =>
              food.name.toLowerCase().contains(normalizedQuery) ||
              food.category.toLowerCase().contains(normalizedQuery),
        )
        .toList();
  }
